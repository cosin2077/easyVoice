const PREFERRED = ['zh-CN', 'zh-TW', 'zh-HK', 'en-US', 'en-GB', 'en-AU', 'en-CA', 'ja-JP', 'ko-KR', 'fr-FR', 'de-DE', 'es-ES', 'pt-BR', 'ru-RU']

export function localeFromVoiceName(name: string): string | null {
  const m = name.match(/^([a-z]{2,3}-[A-Z]{2})/)
  return m ? m[1] : null
}

export function localeLabel(code: string): string {
  return LOCALE_LABELS[code] || code
}

/** Group key for select optgroup: language family display. */
export function localeGroup(code: string): string {
  const lang = code.split('-')[0]
  const map: Record<string, string> = {
    zh: '中文', en: '英语', ja: '日语', ko: '韩语', fr: '法语', de: '德语',
    es: '西班牙语', pt: '葡萄牙语', ru: '俄语', ar: '阿拉伯语', hi: '印度语言',
    th: '东南亚', vi: '东南亚', id: '东南亚', ms: '东南亚', fil: '东南亚',
  }
  return map[lang] || '其他语言'
}

export function buildLanguageOptions(voices: { Name: string }[]) {
  const set = new Set<string>()
  for (const v of voices) {
    const loc = localeFromVoiceName(v.Name)
    if (loc) set.add(loc)
  }
  const all = [...set]
  all.sort((a, b) => {
    const ia = PREFERRED.indexOf(a)
    const ib = PREFERRED.indexOf(b)
    if (ia >= 0 || ib >= 0) return (ia < 0 ? 999 : ia) - (ib < 0 ? 999 : ib)
    const ga = localeGroup(a).localeCompare(localeGroup(b), 'zh')
    if (ga !== 0) return ga
    return localeLabel(a).localeCompare(localeLabel(b), 'zh')
  })
  return all.map((code) => ({
    code,
    name: localeLabel(code),
    group: localeGroup(code),
  }))
}
